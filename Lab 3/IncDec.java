import java.util.*;

class IncDec{
	public static void main(String args[]){
		int i = 2;
	System.out.println(i);
	System.out.println("Pre-Increment : " + (++i));
	System.out.println("Post-Increment : " + (i++));
	System.out.println("Pre-Decrement : " + (--i));
	System.out.println("Pre-Decrement : " + (i--));
	System.out.println(i);
}
}